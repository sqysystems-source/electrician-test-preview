export function contactLink(channel, message = '') {
  if (channel === 'whatsapp') {
    const digits = CONTACT.whatsappPhone.replace(/\D/g, '');
    return `${CONTACT.endpoints.whatsapp}${digits}${message ? `?text=${encodeURIComponent(message)}` : ''}`;
  }
  if (channel === 'viber') return CONTACT.endpoints.viber + encodeURIComponent(CONTACT.viberPhone);
  if (channel === 'emergency-phone') return CONTACT.endpoints.phone + CONTACT.emergencyPhone;
  return CONTACT.endpoints.phone + CONTACT.phone;
}

